"""names.py - display names for Sky Paschalion in English and liturgical languages.

Contract objects
----------------
NAMES[key][lang]        feast/fast keys of feasts.py -> {'en': ..., 'la'|'grc'|'cu'|'cop'|'gez'|'xcl'|'syc'|'ar': ...}
MONTHS[cal][lang]       list of month names; 12 for gregorian/julian/revised_julian/byzantine, 13 for coptic/ethiopian
                        (the byzantine calendar uses the Julian month names; its year order starting 1 September is
                        an Engine concern).
WEEKDAYS[lang]          7 names, MONDAY FIRST (index = datetime.date.weekday()).
HOURS[system][lang]     names in the order of HOUR_KEYS[system] (keys and order copied from the Engine's
                        sky_layer.HOURS_DEFS, so HOURS[s]['en'][i] names canonical_hours(...)[i]['key']).
UNCERTAIN               set of (key, lang) for every native form NOT checked against a cited source.
                        Keys: feast keys as in NAMES; 'month:<cal>:<n>' (n = 1..13); 'weekday:<i>' (0 = Monday);
                        'hour:<system>:<hourkey>'. MONTHS for gregorian/revised_julian/byzantine share the
                        'month:julian:<n>' keys.
label(key, lang)        'English · native' (English alone when lang == 'en' or no native form exists).

Verification (15 Nov 2026)
--------------------------
* Coptic (Bohairic + Arabic) and Ethiopian (Ge'ez script) month names: copied from the month tables of
  https://en.wikipedia.org/wiki/Coptic_calendar and https://en.wikipedia.org/wiki/Ethiopian_calendar .
* Syriac and Levantine-Arabic names of the Julian/Gregorian months: https://en.wikipedia.org/wiki/Assyrian_calendar .
* Two feast forms were checked by hand against the native-script spelling given in an English Wikipedia
  article instead of Wiktionary: ('meskel', 'gez') -> https://en.wikipedia.org/wiki/Meskel and
  ('sawma_rabba', 'syc') -> https://en.wikipedia.org/wiki/Sawma_Rabba (see VERIFIED for the URLs).
* Everything else was looked up automatically in English Wiktionary: a form is VERIFIED only if a page with
  exactly that title (or its lower-case / unpointed / unaccented variant) exists under the language header
  (Latin; Ancient Greek or Greek; Old Church Slavonic or Church Slavonic; Coptic; Ge'ez; Old Armenian or
  Armenian; Classical Syriac or Aramaic; Arabic). This proves the word exists in that language, not that it
  is the exact liturgical title - multi-word titles (Missal headings, Greek/Slavonic feast titles) mostly
  could not be checked and are therefore in UNCERTAIN.
* Church Slavonic is written in plain modern Church Slavonic orthography WITHOUT stress marks or titla and
  was NOT checked against Ponomar texts; nearly all cu forms are in UNCERTAIN.
* Syriac is stored in Unicode Syriac letters; Estrangela / Serto / Madnhaya is a font choice
  (sects.TRADITIONS[...]['syriac_script']).
* Coptic hour names and most Coptic feast names are omitted rather than guessed (label() falls back to English).
"""

