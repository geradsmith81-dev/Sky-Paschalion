SEP = " \u00b7 "


def native(key, lang):
    """Native form or None."""
    return NAMES.get(key, {}).get(lang)


def label(key, lang):
    """'English · native' for a feast/fast key; English alone if no form exists for lang."""
    d = NAMES.get(key)
    if d is None:
        return key.replace("_", " ")
    en = d.get("en", key)
    nat = d.get(lang) if lang != "en" else None
    return en + SEP + nat if nat else en


def is_uncertain(key, lang):
    return (key, lang) in UNCERTAIN


def _month_key(cal, n):
    return "month:%s:%d" % ("julian" if cal in ("gregorian", "revised_julian", "byzantine") else cal, n)


def month_label(cal, n, lang):
    """'English · native' month name; n is 1-based (13 = epagomenal month)."""
    m = MONTHS[cal]
    en = m["en"][n - 1]
    if lang != "en" and lang in m:
        return en + SEP + m[lang][n - 1]
    return en


def weekday_label(d, lang):
    """'English · native' weekday of a datetime.date."""
    i = d.weekday()
    en = WEEKDAYS["en"][i]
    return en + SEP + WEEKDAYS[lang][i] if lang != "en" and lang in WEEKDAYS else en


def hour_label(system, hour_key, lang):
    keys = HOUR_KEYS[system]
    i = keys.index(hour_key)
    en = HOURS[system]["en"][i]
    nat = HOURS[system].get(lang)
    return en + SEP + nat[i] if lang != "en" and nat else en


def uncertain_table():
    """Rows (key, lang, form) of every unverified form, for the About page."""
    rows = []
    for key, lang in sorted(UNCERTAIN):
        if key.startswith("month:"):
            _, cal, n = key.split(":")
            form = MONTHS[cal][lang][int(n) - 1]
        elif key.startswith("weekday:"):
            form = WEEKDAYS[lang][int(key.split(":")[1])]
        elif key.startswith("hour:"):
            _, s, hk = key.split(":")
            form = HOURS[s][lang][HOUR_KEYS[s].index(hk)]
        else:
            form = NAMES[key][lang]
        rows.append((key, lang, form))
    return rows
