DEFAULT_TRADITION = "latin_catholic"

BY_KEY = {t["key"]: t for t in TRADITIONS}


def get(key):
    """Return the tradition dict for key (KeyError if unknown)."""
    return BY_KEY[key]


def by_communion(communion_key):
    """List the traditions of one communion, in TRADITIONS order."""
    return [t for t in TRADITIONS if t["communion"] == communion_key]


def preset(key):
    """Settings applied by the Traditions page 'Use' button.

    Returns dict(fixed_calendar, paschalion, lang, hours_system) - lang is the
    first entry of liturgical_languages (the display default).
    """
    t = BY_KEY.get(key) or BY_KEY[DEFAULT_TRADITION]
    return {"fixed_calendar": t["fixed_calendar"], "paschalion": t["paschalion"],
            "lang": t["liturgical_languages"][0], "hours_system": t["hours_system"]}


def tree():
    """Communion -> list of (key, name_en) for drawing the branch diagram."""
    return {c["key"]: [(t["key"], t["name_en"]) for t in by_communion(c["key"])] for c in COMMUNIONS}
